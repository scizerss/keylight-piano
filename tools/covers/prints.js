// Builds renderer/cover-prints.js: a small "fingerprint" of every built-in song (its first notes, tempo, key
// guess, density) so the cover generator (renderer/cover-art.js) can draw a cover without opening 76 files.
//   node tools/covers/prints.js
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const root = path.join(__dirname, '..', '..')

// a tiny XML DOM, enough for musicxml.js (Node has no DOMParser); same idea as scripts/test-song-import.js
function parseXml(src) {
  const rootEl = { tagName: '#doc', children: [], attrs: {}, text: '', parent: null }
  let cur = rootEl
  const re = /<!--[\s\S]*?-->|<\?[\s\S]*?\?>|<!DOCTYPE[^>]*>|<\/([\w:.-]+)\s*>|<([\w:.-]+)((?:\s+[\w:.-]+\s*=\s*"[^"]*")*)\s*(\/?)>|([^<]+)/g
  let m
  while ((m = re.exec(src))) {
    if (m[1]) cur = cur.parent
    else if (m[2]) {
      const el = { tagName: m[2], children: [], attrs: {}, text: '', parent: cur }
      for (const a of m[3].matchAll(/([\w:.-]+)\s*=\s*"([^"]*)"/g)) el.attrs[a[1]] = a[2]
      cur.children.push(el)
      if (!m[4]) cur = el
    } else if (m[5]) cur.text += m[5]
  }
  const walk = (el) => {
    el.getAttribute = (n) => (n in el.attrs ? el.attrs[n] : null)
    el.hasAttribute = (n) => n in el.attrs
    Object.defineProperty(el, 'textContent', { get: () => el.text + el.children.map((c) => c.textContent).join('') })
    Object.defineProperty(el, 'nextElementSibling', { get: () => { const s = el.parent.children; return s[s.indexOf(el) + 1] || null } })
    const all = () => el.children.flatMap((c) => [c, ...c.querySelectorAll('*')])
    el.querySelectorAll = (sel) => {
      if (sel === '*') return all()
      const chain = sel.split('>').map((s) => s.trim())
      return all().filter((n) => {
        let x = n
        for (let i = chain.length - 1; i >= 0; i--) { if (!x || x === el || x.tagName !== chain[i]) return false; x = x.parent }
        return true
      })
    }
    el.querySelector = (sel) => el.querySelectorAll(sel)[0] || null
    el.children.forEach(walk)
  }
  walk(rootEl)
  rootEl.documentElement = rootEl.children[0]
  return rootEl
}
globalThis.DOMParser = class { parseFromString(s) { return parseXml(s) } }

;(async () => {
  const imp = (p) => import(pathToFileURL(path.join(root, p)).href)
  const { parseSongFile, normalise } = await imp('renderer/songloader.js')
  const { fingerprintOf } = await imp('renderer/cover-art.js')
  const { MUTOPIA_SONGS } = await imp('renderer/songs-mutopia.js')
  const app = fs.readFileSync(path.join(root, 'renderer/app.js'), 'utf8')
  const files = [...app.matchAll(/^\s*\{ file: '([^']+\.xml)'/gm)].map((m) => m[1]).concat(MUTOPIA_SONGS.map((s) => s.file))
  const out = {}
  for (const f of files) {
    const buf = fs.readFileSync(path.join(root, 'renderer/songs', f))
    const file = { name: f, arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), text: async () => buf.toString('utf8') }
    const song = normalise(f, await parseSongFile(file))
    out[f] = fingerprintOf(song)
  }
  const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')
  fs.writeFileSync(path.join(root, 'renderer/cover-prints.js'),
    `// GENERATED by tools/covers/prints.js: the opening notes and a few numbers of each built-in song, for renderer/cover-art.js.\n// Re-run it after adding a song. Format: see fingerprintOf() in cover-art.js.\nexport const COVER_PRINTS = {\n${body}\n}\n`)
  console.log('prints:', files.length, 'songs,', fs.statSync(path.join(root, 'renderer/cover-prints.js')).size, 'bytes')
})()
