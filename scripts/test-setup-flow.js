test('device rows: connect, spinner, 8 s timeout, identify twins', async () => {
  const F = await load('setup-flow.js')
  const dev = (state, extra = {}) => ({ id: 'a', name: 'LUMI Keys 1', state, ...extra })
  assert.equal(F.rowView(dev('found')).action, 'connect')
  assert.equal(F.rowView(dev('found', { known: true })).status, 'Used before')
  const tapped = F.rowView(dev('found'), { since: 1000, now: 3000 })
  assert.ok(tapped.busy && !tapped.action, 'a tap shows a spinner at once, before the device answers')
  assert.ok(F.rowView(dev('connecting'), { since: 1000, now: 5000 }).busy)
  const late = F.rowView(dev('connecting'), { since: 1000, now: 1000 + F.CONNECT_TIMEOUT_MS })
  assert.equal(late.button, 'Try again'); assert.equal(late.tone, 'warn')
  assert.equal(F.rowView(dev('connected'), { since: 1000, now: 99999 }).tone, 'ok', 'connected beats the timeout')
  assert.equal(F.rowView(dev('connected')).action, null, 'one keyboard: nothing to identify')
  assert.equal(F.rowView(dev('connected'), { several: true }).action, 'identify')
  assert.ok(F.rowView(dev('reconnecting')).busy)
  assert.equal(F.rowView(dev('lost')).action, 'connect')
  assert.ok(F.rowView(dev('lost'), { since: 1000, now: 2000 }).busy, 'Connect on a lost keyboard shows the spinner too')
  for (const state of ['connecting', 'found', 'lost']) assert.equal(F.rowView(dev(state), { since: -1, now: 3000 }).button, 'Try again', 'a failed attempt says so at once, even in the first seconds after launch: ' + state)
  assert.equal(F.rowView(dev('lost'), { since: 1000, now: 1000 + F.CONNECT_TIMEOUT_MS }).button, 'Try again', 'and can time out')
  const sorted = F.sortDevices([{ id: '2', name: 'LUMI Keys 2', state: 'found' }, { id: '1', name: 'LUMI Keys 1', state: 'found' }, { id: '3', name: 'ROLI Piano', state: 'connected' }, null])
  assert.deepEqual(sorted.map((d) => d.id), ['3', '1', '2'])
})

test('connection banner: no flicker on reopen, lost, reconnecting, reconnected, never stays', async () => {
  const F = await load('setup-flow.js')
  let s = F.bannerStart()
  s = F.bannerTick(F.bannerEvent(s, { connected: false }, 0), 5000)
  assert.equal(s.show, null, 'no keyboard at launch is not a lost keyboard')
  s = F.bannerEvent(s, { connected: true, name: 'LUMI Keys' }, 100)
  s = F.bannerEvent(s, { connected: false }, 1000)
  s = F.bannerTick(s, 1000 + F.LOST_GRACE_MS - 1)
  assert.equal(s.show, null, 'a port reopening within the grace time shows nothing')
  s = F.bannerEvent(s, { connected: true }, 1600)
  s = F.bannerTick(s, 1700)
  assert.equal(s.show, null, 'and coming straight back is not "Reconnected"')
  s = F.bannerTick(F.bannerEvent(s, { connected: false }, 2000), 2000 + F.LOST_GRACE_MS)
  assert.equal(s.show, 'lost')
  assert.match(F.bannerText(s).text, /^LUMI Keys disconnected\. Turn it back on and Keylight reconnects\.$/)
  s = F.bannerEvent(s, { connected: false, reconnecting: true }, 4000)
  assert.equal(s.show, 'reconnecting'); assert.ok(F.bannerText(s).spin)
  s = F.bannerEvent(s, { connected: true }, 4500)
  assert.equal(s.show, 'reconnected'); assert.equal(F.bannerText(s).text, 'Reconnected')
  s = F.bannerTick(s, 4500 + F.RECONNECTED_MS)
  assert.equal(s.show, null, 'Reconnected goes after 2 s')
  s = F.bannerTick(F.bannerEvent(s, { connected: false }, 10000), 10000 + F.LOST_GRACE_MS)
  s = F.bannerTick(s, 10000 + F.LOST_GRACE_MS + F.SHOW_MAX_MS)
  assert.equal(s.show, null, 'a lost notice does not cover the player for long')
  s = F.bannerTick(s, 30000)
  assert.equal(s.show, null, 'and does not come back by itself')
  s = F.bannerEvent(s, { connected: true }, 40000)
  assert.equal(s.show, 'reconnected', 'coming back after the notice went still says Reconnected')
  // still off long after the notice went: switching it back on says "Reconnecting" again
  s = F.bannerTick(F.bannerEvent(s, { connected: false }, 50000), 50000 + F.LOST_GRACE_MS)
  s = F.bannerTick(s, 50000 + F.LOST_GRACE_MS + F.SHOW_MAX_MS)
  assert.equal(s.show, null)
  s = F.bannerEvent(s, { connected: false, reconnecting: true }, 70000)
  assert.equal(s.show, 'reconnecting', 'a fresh reconnect attempt is shown after the lost notice timed out')
  s = F.bannerEvent(s, { connected: false, reconnecting: false }, 71000)
  assert.equal(s.reconnecting, false, 'a failed attempt clears the reconnecting flag')
  assert.equal(s.show, null, 'and its spinner goes with it')
  // a second loss after reconnecting is a new loss
  s = F.bannerEvent(s, { connected: true }, 80000)
  s = F.bannerTick(F.bannerEvent(s, { connected: false }, 90000), 90000 + F.LOST_GRACE_MS)
  assert.equal(s.show, 'lost', 'each loss gets its own notice')
  for (const show of ['lost', 'reconnecting', 'reconnected']) assert.doesNotMatch(F.bannerText({ show, name: 'X' }).text, /—/)
})

