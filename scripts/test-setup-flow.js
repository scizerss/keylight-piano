test('a Bluetooth row claims only a Bluetooth port with the same name', () => {
  // The pure rule lives inside setupDeviceRows (app.js); run just that slice, as test-pair-midi.js does.
  const source = readFileSync(path.join(__dirname, '..', 'renderer', 'app.js'), 'utf8')
  const slice = source.slice(source.indexOf('const kbName = '), source.indexOf('const taken = new Set()'))
  assert.ok(slice.includes('sameKb') && slice.includes('blePort'), 'the slice still holds the naming rules')
  const ctx = vm.createContext({ __kb: null })
  vm.runInContext(slice + '\n__kb = { kbName, sameKb, blePort }', ctx, { filename: 'renderer/app.js (device row naming)' })
  const { kbName, sameKb, blePort } = ctx.__kb

  assert.equal(kbName('LUMI Keys BLOCK Bluetooth'), 'lumi keys', 'the Mac port suffix and BLOCK both come off')
  assert.ok(sameKb('LUMI Keys BLOCK Bluetooth', 'LUMI Keys 1'), 'a numbered Bluetooth name matches its block port')
  assert.ok(sameKb('LUMI Keys BLOCK', 'LUMI Keys 1'), 'and the port without the suffix does too')
  assert.ok(sameKb('ROLI Piano BLOCK', 'ROLI Piano'), 'the plain containment rule still holds')
  assert.ok(!sameKb('ROLI Piano', 'LUMI Keys 1'), 'different keyboards do not match')
  assert.ok(!sameKb('Bluetooth Keyboard', 'LUMI Keys 1'), 'the generic iOS name never matches')

  assert.equal(blePort({ name: 'LUMI Keys BLOCK', transport: 'usb' }), false, 'a USB port is never claimed by a Bluetooth row')
  assert.equal(blePort({ name: 'LUMI Keys BLOCK', transport: 'ble' }), true)
  assert.equal(blePort({ name: 'LUMI Keys BLOCK' }), true, 'desktop Web MIDI has no transport and goes by the name')
})
