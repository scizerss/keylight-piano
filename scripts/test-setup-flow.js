test('one ROLI or LUMI choice; old ids map onto the new ones', async () => {
  const P = await load('keyboard-profiles.js')
  assert.deepEqual(P.listProfiles().map((p) => p.id), ['roli', 'partykeys', 'midi', 'screen'])
  for (const old of ['lumi24', 'piano49', 'two24']) assert.equal(P.normalizeChoice(old), 'roli', old)
  assert.equal(P.normalizeChoice('other'), 'midi')
  for (const odd of ['', 'nope', null, undefined, 3]) assert.equal(P.normalizeChoice(odd), '', String(odd))
  assert.equal(P.profileById('lumi24').id, 'roli', 'a saved lumi24 still reads as a choice')
  assert.equal(P.profileById('other').id, 'midi')
  assert.equal(P.profileById('roli').keys, 0, 'ROLI or LUMI leaves the count on Automatic (24, 48 or 49 is read from the keyboard)')
  assert.equal(P.profileById('screen').keys, null)
  // the PartyKeys card: Automatic keys, lights on (beta), a connect step like any keyboard, and the lights wording stays beta until the hardware test
  const party = P.profileById('partykeys')
  assert.deepEqual([party.keys, party.lights, party.detail], [0, true, 'Lights: beta'])
  assert.deepEqual(P.stepsFor('partykeys'), ['pick', 'connect', 'ready'])
  assert.equal(P.normalizeChoice('partykeys'), 'partykeys')
  assert.doesNotMatch(party.sub + party.detail, /[—–]/, 'no em dash in the card')
  assert.match(P.listProfiles(false, { touch: true }).at(-1).sub, /iPhone or iPad/)
  assert.doesNotMatch(P.listProfiles().at(-1).sub, /iPhone/, 'desktop wording for the on-screen keys')
  for (const p of P.listProfiles()) assert.match(P.glyphSVG(p.glyph), /^<svg /)
  const copy = P.listProfiles(); copy[0].name = 'changed'
  assert.notEqual(P.listProfiles()[0].name, 'changed', 'listProfiles hands out copies')
})

test('steps per choice: a keyboard is connected, the screen finishes at once', async () => {
  const F = await load('setup-flow.js')
  assert.deepEqual(F.planFor('roli'), ['welcome', 'pick', 'connect', 'level', 'ready'])
  assert.deepEqual(F.planFor('midi'), ['welcome', 'pick', 'connect', 'level', 'ready'])
  assert.deepEqual(F.planFor('lumi24'), ['welcome', 'pick', 'connect', 'level', 'ready'], 'old id')
  assert.deepEqual(F.planFor('screen'), ['welcome', 'pick', 'level'], 'on-screen keys: the level question after the picker')
  assert.deepEqual(F.planFor(''), ['welcome', 'pick'], 'nothing chosen yet: the picker is the last step known')
  assert.deepEqual(F.planFor('roli', { first: false }), ['pick', 'connect', 'ready'], 'run from Settings: no welcome and no level question')
  assert.deepEqual(F.planFor('screen', { first: false }), ['pick'], 'run from Settings never asks the level again')
  assert.deepEqual(F.planFor('roli', { connectOnly: true }), ['connect'], 'Settings > Connect a Bluetooth keyboard')
  assert.equal(F.nextStep(F.planFor('roli'), 'welcome'), 'pick')
  assert.equal(F.nextStep(F.planFor('roli'), 'pick'), 'connect')
  assert.equal(F.nextStep(F.planFor('roli'), 'connect'), 'level')
  assert.equal(F.nextStep(F.planFor('roli'), 'level'), 'ready')
  assert.equal(F.nextStep(F.planFor('roli'), 'ready'), null, 'finished')
  assert.equal(F.nextStep(F.planFor('screen'), 'pick'), 'level')
  assert.equal(F.nextStep(F.planFor('screen'), 'level'), null, 'on-screen keys finish from the level question')
  for (const plan of [F.planFor('roli'), F.planFor('screen'), F.planFor('midi', { first: false })]) for (const s of plan) assert.ok(F.SETUP_STEPS.includes(s), s)
})

