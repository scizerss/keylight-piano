test('Back returns to the step you came from and keeps the choice', async () => {
  const F = await load('setup-flow.js')
  const settings = { kbChoice: '' }
  let history = ['welcome']
  assert.equal(F.canGoBack(history), false, 'nothing to go back to on the welcome')
  history = F.pushStep(history, F.nextStep(F.planFor(settings.kbChoice), 'welcome'))
  settings.kbChoice = 'roli'
  history = F.pushStep(history, F.nextStep(F.planFor(settings.kbChoice), 'pick'))
  assert.deepEqual(history, ['welcome', 'pick', 'connect'])
  assert.deepEqual(F.pushStep(history, 'connect'), history, 'the same step twice is one entry')
  history = F.backStep(history)
  assert.equal(history.at(-1), 'pick')
  assert.equal(settings.kbChoice, 'roli', 'the choice is still made')
  settings.kbChoice = 'midi'   // change your mind on the way back
  history = F.pushStep(history, F.nextStep(F.planFor(settings.kbChoice), 'pick'))
  assert.deepEqual(history, ['welcome', 'pick', 'connect'])
  history = F.pushStep(history, F.nextStep(F.planFor(settings.kbChoice), 'connect'))
  assert.deepEqual(history, ['welcome', 'pick', 'connect', 'level'])
  history = F.backStep(history)
  assert.equal(history.at(-1), 'connect', 'Back from the level question returns to connect')
  history = F.backStep(F.backStep(F.backStep(history)))
  assert.deepEqual(history, ['welcome'], 'Back never empties the history')
})

